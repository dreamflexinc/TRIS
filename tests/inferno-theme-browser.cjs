'use strict';
const {chromium}=require('playwright'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),out=path.join(root,'test-results');fs.mkdirSync(out,{recursive:true});
const results=[],errors=[];let browser;
const pass=name=>{results.push(name);console.log('PASS '+name);};
(async()=>{
  browser=await chromium.launch({headless:true,channel:'msedge'});
  const context=await browser.newContext({viewport:{width:1500,height:1100},reducedMotion:'reduce'});
  const page=await context.newPage();page.on('pageerror',error=>errors.push(error.message));
  await page.route('https://inferno-theme.test/',route=>route.fulfill({path:path.join(root,'TRIScore4_3_InfernoLab.html'),contentType:'text/html'}));
  await page.goto('https://inferno-theme.test/');
  const first=await page.evaluate(()=>({theme:GoblinColorStudio.getState(),graphs:GoblinGraphs.getState(),preset:TRIScoreInfernoTheme.inspect(),backup:JSON.parse(localStorage.getItem('triscore-inferno-previous-appearance-v1'))}));
  assert.equal(first.theme.dark.color,'#FF793F');assert.equal(first.graphs.dark.curve1,'#FFA34D');assert(first.preset.hasBackup);
  pass('Inferno boots with ember and charcoal palettes and saves previous appearance');
  await page.evaluate(()=>{go('colors');document.querySelector('[data-cs-mode="dark"]').click();const input=document.getElementById('cs-hex-dark');input.value='#29AADD';input.dispatchEvent(new Event('change',{bubbles:true}));});
  await page.waitForTimeout(250);await page.reload();
  assert.equal(await page.evaluate(()=>GoblinColorStudio.getState().dark.color),'#29AADD');
  pass('A user-selected color remains editable and survives reload without preset override');
  assert(await page.evaluate(()=>TRIScoreInfernoTheme.restore()));
  const restored=await page.evaluate(()=>({theme:GoblinColorStudio.getState(),graphs:GoblinGraphs.getState()}));
  assert.deepEqual(restored.theme,first.backup.theme);assert.deepEqual(restored.graphs,first.backup.graphs);
  await page.reload();assert.deepEqual(await page.evaluate(()=>GoblinColorStudio.getState()),first.backup.theme);
  pass('Restoring previous colors recovers exact theme and graph settings and persists');
  assert(await page.evaluate(()=>TRIScoreInfernoTheme.apply()));
  assert.equal(await page.evaluate(()=>GoblinColorStudio.getState().dark.color),'#FF793F');
  assert.deepEqual(await page.evaluate(()=>JSON.parse(localStorage.getItem('triscore-inferno-previous-appearance-v1'))),first.backup);
  pass('Reapplying Inferno retains the original recovery copy');
  assert.deepEqual(errors,[]);pass('Appearance controls initialize without renderer exceptions');
  fs.writeFileSync(path.join(out,'inferno-theme-browser-results.json'),JSON.stringify({passed:results.length,results,errors},null,2));
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(async()=>{if(browser)await browser.close();});
